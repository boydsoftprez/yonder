import { chromium } from "playwright";
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1512, height: 900 } });
const errs = []; p.on("pageerror", e => errs.push(e.message));
await p.goto("http://127.0.0.1:18930/index.html", { waitUntil: "networkidle" });
await p.getByRole("button", { name: /pocket 2/i }).click(); await p.waitForTimeout(300);
const order = async () => (await p.locator(".d-cols .d-col .d-h span:first-child").allInnerTexts()).join(" > ");
const box = async (t) => { const el = p.locator(".d-col", { hasText: t }); return (await el.count()) ? JSON.stringify(await el.boundingBox()) : "MISSING"; };
console.log("order   :", await order());
console.log("preview :", await box("PREVIEW"));
const prevSeg = p.locator(".d-col", { hasText: "PREVIEW" }).locator(".d-seg__b");
await prevSeg.filter({ hasText: "Fixed" }).click(); await p.waitForTimeout(200);
console.log("-- preview set Fixed --");
console.log("order   :", await order());
console.log("preview :", await box("PREVIEW"));
await prevSeg.filter({ hasText: "Adaptive" }).click(); await p.waitForTimeout(200);
console.log("-- preview set Adaptive --");
console.log("order   :", await order());
console.log("preview :", await box("PREVIEW"));
console.log("picture :", JSON.stringify(await p.locator(".d-vid").boundingBox()));
console.log("state   :", (await p.locator(".d-state").innerText()).replace(/\n/g," / "));
console.log(errs.length ? "ERRORS: " + errs.join(" | ") : "no errors");
await b.close();
